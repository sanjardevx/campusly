#!/usr/bin/env bash
# Builds backend/.env.production on the EC2 box from SSM Parameter Store (/campusly/prod/*).
# The box reads them with its IAM role (campusly-ec2) — no access keys, nothing copied by hand.
# Run it again after changing a parameter, then restart: docker compose -f docker-compose.prod.yml up -d
#
#   bash deploy/env-from-ssm.sh        (from backend/)
set -euo pipefail

SSM_PATH=/campusly/prod/
OUT="$(cd "$(dirname "$0")/.." && pwd)/.env.production"

json=$(aws ssm get-parameters-by-path --region eu-central-1 \
  --path "$SSM_PATH" --recursive --with-decryption --output json)

# One KEY='value' line per parameter. Single quotes: Docker Compose takes the value as is
# (no $ interpolation). A multi-line value (the CloudFront PEM key) becomes one line with
# literal \n, which StorageService turns back into newlines.
umask 077 # the file is readable by this user only (chmod 600)
python3 -c '
import json, sys
params = sorted(json.load(sys.stdin)["Parameters"], key=lambda p: p["Name"])
if not params:
    sys.exit("No parameters under /campusly/prod/ (or the role cannot read them)")
print("# Generated by deploy/env-from-ssm.sh from SSM /campusly/prod/ - do not edit, re-run the script")
for p in params:
    key = p["Name"].rsplit("/", 1)[-1]
    value = p["Value"].strip().replace("\n", "\\n")
    if "\x27" in value:
        sys.exit(f"{key}: single quotes are not allowed in values")
    print(f"{key}=\x27{value}\x27")
' <<<"$json" >"$OUT.tmp"
mv "$OUT.tmp" "$OUT" # replace the old file only when the new one is complete

# Names only, never the values
echo "Wrote $OUT with: $(grep -o '^[A-Z0-9_]*' "$OUT" | tr '\n' ' ')"
